"""Owner's Illustrator artwork (tools/brand/wine.svg, from wine.ai via pdftocairo -svg) ->
   Jeroboam/Sources/BrandShapes.swift (SwiftUI shapes) + the 1024 app icon (cairosvg, anti-aliased)."""
import re, os, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.join(HERE, "..", "..")
svg = open(os.path.join(HERE, "wine.svg")).read()
pages = re.findall(r"<page>(.*?)</page>", svg, re.S)
def paths(page): return re.findall(r'd="([^"]+)"', page)
def tokens(d): return re.findall(r"[MLCZ]|-?\d+(?:\.\d+)?", d)
def parse(d):
    t = tokens(d); i = 0; out = []
    while i < len(t):
        c = t[i]; i += 1
        if c == "M": out.append(("M", [(float(t[i]), float(t[i+1]))])); i += 2
        elif c == "L": out.append(("L", [(float(t[i]), float(t[i+1]))])); i += 2
        elif c == "C": out.append(("C", [(float(t[i+k]), float(t[i+k+1])) for k in (0, 2, 4)])); i += 6
        elif c == "Z": out.append(("Z", []))
        else:  # implicit repeat (not produced by cairo)
            raise ValueError(c)
    return out
def bbox(cmds_list):
    xs = [p[0] for cmds in cmds_list for _, ps in cmds for p in ps]; ys = [p[1] for cmds in cmds_list for _, ps in cmds for p in ps]
    return min(xs), min(ys), max(xs), max(ys)
def swift(cmds, box, name):
    x0, y0, x1, y1 = box; w = x1 - x0; h = y1 - y0
    f = lambda p: f"P({(p[0]-x0)/w:.5f}, {(p[1]-y0)/h:.5f})"
    lines = []
    for c, ps in cmds:
        if c == "M": lines.append(f"        p.move(to: {f(ps[0])})")
        elif c == "L": lines.append(f"        p.addLine(to: {f(ps[0])})")
        elif c == "C": lines.append(f"        p.addCurve(to: {f(ps[2])}, control1: {f(ps[0])}, control2: {f(ps[1])})")
        else: lines.append("        p.closeSubpath()")
    return "\n".join(lines)

splash = [parse(d) for d in paths(pages[0])]          # body, droplet
glass_paths = [parse(d) for d in paths(pages[1])]     # outline (with bowl hole), wine
sb = bbox(splash); gb = bbox(glass_paths)
# splash box made square (centered) so it keeps its proportions in any square frame
sx0, sy0, sx1, sy1 = sb; side = max(sx1 - sx0, sy1 - sy0)
sq = ((sx0 + sx1 - side) / 2, (sy0 + sy1 - side) / 2, (sx0 + sx1 + side) / 2, (sy0 + sy1 + side) / 2)
gx0, gy0, gx1, gy1 = gb
ga = (gx1 - gx0) / (gy1 - gy0)
wine_top = min(p[1] for _, ps in glass_paths[1] for p in ps); wine_bot = max(p[1] for _, ps in glass_paths[1] for p in ps)
code = f'''import SwiftUI

// Generated by tools/brand/build_brand.py from the owner's Illustrator artwork (wine.ai). Do not edit by hand.

/// The Jero splash, body only (square frame).
struct SplashBodyShape: Shape {{
    func path(in rect: CGRect) -> Path {{
        let s = min(rect.width, rect.height)
        let ox = rect.midX - s / 2, oy = rect.midY - s / 2
        func P(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{ CGPoint(x: ox + x * s, y: oy + y * s) }}
        var p = Path()
{swift(splash[0], sq, "body")}
        return p
    }}
}}

/// The droplet above the splash (square frame, same coordinates as the body).
struct SplashDropShape: Shape {{
    func path(in rect: CGRect) -> Path {{
        let s = min(rect.width, rect.height)
        let ox = rect.midX - s / 2, oy = rect.midY - s / 2
        func P(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{ CGPoint(x: ox + x * s, y: oy + y * s) }}
        var p = Path()
{swift(splash[1], sq, "drop")}
        return p
    }}
}}

/// The glass outline (stem, foot and an open bowl), in a frame of aspect {ga:.4f}.
struct GlassOutlineShape: Shape {{
    static let aspect: CGFloat = {ga:.4f}
    func path(in r: CGRect) -> Path {{
        func P(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{ CGPoint(x: r.minX + x * r.width, y: r.minY + y * r.height) }}
        var p = Path()
{swift(glass_paths[0], gb, "glass")}
        return p
    }}
}}

/// The wine inside the glass (same frame as the outline). Its flat top sits at y = {(wine_top-gy0)/(gy1-gy0):.4f}.
struct GlassWineShape: Shape {{
    static let top: CGFloat = {(wine_top-gy0)/(gy1-gy0):.5f}
    static let bottom: CGFloat = {(wine_bot-gy0)/(gy1-gy0):.5f}
    func path(in r: CGRect) -> Path {{
        func P(_ x: CGFloat, _ y: CGFloat) -> CGPoint {{ CGPoint(x: r.minX + x * r.width, y: r.minY + y * r.height) }}
        var p = Path()
{swift(glass_paths[1], gb, "wine")}
        return p
    }}
}}
'''
open(os.path.join(ROOT, "Jeroboam", "Sources", "BrandShapes.swift"), "w").write(code)

# App icon: Bordeaux ground, white splash, cork-beige droplet (owner: "white and an off-white for the inner one")
import cairosvg
ds = paths(pages[0])
pad = 0.2
S = 1024; inner = S * (1 - 2 * pad); k = inner / side
tx = S * pad - sq[0] * k; ty = S * pad - sq[1] * k
icon = f'''<svg xmlns="http://www.w3.org/2000/svg" width="{S}" height="{S}" viewBox="0 0 {S} {S}">
<rect width="{S}" height="{S}" fill="#8B1538"/>
<g transform="translate({tx:.2f} {ty:.2f}) scale({k:.5f})">
<path fill="#FFFFFF" d="{ds[0]}"/>
<path fill="#F0D9C4" d="{ds[1]}"/>
</g></svg>'''
open(os.path.join(HERE, "icon.svg"), "w").write(icon)
out = os.path.join(ROOT, "Jeroboam", "Resources", "Assets.xcassets", "AppIcon.appiconset", "icon-1024.png")
cairosvg.svg2png(bytestring=icon.encode(), write_to=out, output_width=S, output_height=S)
print("ok", sb, gb, ga)
